"""Generating a maze set: M mazes from one set seed, each checked and saved (Module A).

Per maze, in <out>/<maze name>/:
    world.sdf     Gazebo world for maze.launch.py world:=... (AR1)
    layout.txt    ASCII layout for make_maze.py (AR2)
    maze.json     metadata and ground truth for Module E (AR13)
    preview.png   picture of walls, exits and start (AR14)
"""

import hashlib
import os

from .. import fileio
from .files import (cell_centre, exit_gap_centre, free_area, ground_plane, layout_is_parseable,
                    layout_text, preview_png, walls_from_layout, world_sdf)
from .generator import GenerationError, derive_seed, exit_boundary_index, generate
from .params import validate

GENERATOR_VERSION = 1
MAX_ATTEMPTS = 1000


def maze_name(index):
    return f'maze-{index:03d}'


def lidar_margin(profile):
    return (profile.lidar_range if profile is not None else 3.5) + 0.5


def generate_checked(params, seed, seen=(), log=None):
    """Generate with `seed`; on a failed check, discard and try the next seed (AR4, AR12)."""
    discarded = []
    for _ in range(MAX_ATTEMPTS):
        try:
            maze = generate(params, seed)
        except GenerationError as exc:
            discarded.append({'seed': seed, 'reason': str(exc)})
            if log:
                log(f'Discarded maze with seed {seed}: {exc}')
            seed += 1
            continue
        problems = maze.check_reachable()
        if not layout_is_parseable(maze):
            problems.append('a wall line of the layout would have no wall at all, which '
                            'make_maze.py drops')
        text = '\n'.join(_layout_key(maze))
        if not problems and text in seen:
            problems.append('duplicate of another maze in the set')
        if not problems:
            return maze, discarded
        discarded.append({'seed': seed, 'reason': '; '.join(problems)})
        if log:
            log(f'Discarded maze with seed {seed}: {"; ".join(problems)}')
        seed += 1
    raise GenerationError(f'No valid maze after {MAX_ATTEMPTS} seeds')


def _layout_key(maze):
    from .files import layout_lines
    return layout_lines(maze) + [f'start {maze.start}']


def metadata(maze, index, set_seed, discarded, plane, walls):
    p = maze.params
    pitch = p.pitch
    dist = maze.distances()
    sx, sy = cell_centre(maze, *maze.start)
    exits = []
    for side, c, r in maze.exits:
        gx, gy = exit_gap_centre(maze, side, c, r)
        steps = dist.get((c, r))
        exits.append({
            'side': side, 'cell': [c, r],
            'gap_centre': [round(gx, 4), round(gy, 4)],
            'boundary_index': exit_boundary_index(maze, (side, c, r)),
            'shortest_path_cells': steps,
            # along corridor centres: cell steps, then half a cell to the gap
            'shortest_path_m': None if steps is None else round(steps * pitch + pitch / 2, 4),
        })
    return {
        'schema_version': fileio.SCHEMA_VERSION,
        'generator_version': GENERATOR_VERSION,
        'index': index,
        'set_seed': set_seed,
        'seed': maze.seed,
        'params': p.to_dict(),
        'grid': {'columns': maze.columns, 'rows': maze.rows, 'pitch': round(pitch, 6),
                 'wall_thickness': p.wall_thickness, 'wall_height': p.wall_height,
                 'origin': 'top-left outer wall corner; rows go toward -y'},
        'start_cell': list(maze.start),
        'spawn': {'x': round(sx, 4), 'y': round(sy, 4), 'yaw': 0.0},
        'exits': exits,
        'walls': {
            'h': [[int(w) for w in row] for row in maze.h],
            'v': [[int(w) for w in row] for row in maze.v],
            'boxes': [[round(x, 4), round(y, 4), round(a, 4), round(b, 4)]
                      for x, y, a, b in walls],
        },
        'free_area_m2': round(free_area(maze), 4),
        'ground_plane': {'center': [round(v, 4) for v in plane['center']],
                         'size': [round(v, 4) for v in plane['size']]},
        'discarded': discarded,
        'files': {'world': 'world.sdf', 'layout': 'layout.txt', 'preview': 'preview.png'},
    }


def build_files(maze, index, set_seed, discarded, profile=None, set_name=''):
    """The four files of one maze, as {name: bytes}."""
    p = maze.params
    comments = [
        f'Generated by maze_experiments (generator {GENERATOR_VERSION}): '
        f'{set_name + ", " if set_name else ""}maze {index}, seed {maze.seed}',
        f'{maze.columns} x {maze.rows} cells, cell pitch {p.pitch:.3f} m '
        f'(corridor {p.corridor_width:.3f} m + wall {p.wall_thickness:.3f} m), '
        f'walls {p.wall_height:.2f} m high',
        f'start cell (column, row) = {maze.start}; exits: '
        + ', '.join(f'{s} of ({c}, {r})' for s, c, r in maze.exits),
        'Cells are 3 characters wide; origin is the top-left corner, rows go toward -y.',
    ]
    if abs(p.pitch - 0.5) > 1e-9 or abs(p.wall_thickness - 0.02) > 1e-9 \
            or abs(p.wall_height - 0.3) > 1e-9:
        comments.append('make_maze.py builds 0.5 m cells with 0.02 m x 0.3 m walls; use '
                        'world.sdf for this geometry.')
    text = layout_text(maze, comments)
    walls = walls_from_layout(text, p.pitch, p.wall_thickness)
    plane = ground_plane(maze.columns, maze.rows, p.pitch, p.wall_thickness,
                         lidar_margin(profile))
    meta = metadata(maze, index, set_seed, discarded, plane, walls)
    import json
    return {
        'world.sdf': world_sdf(text, p.pitch, p.wall_thickness, p.wall_height, plane).encode(),
        'layout.txt': text.encode(),
        'maze.json': (json.dumps(meta, indent=2) + '\n').encode(),
        'preview.png': preview_png(maze, walls),
    }


def generate_set(params, set_seed, count, out_dir, profile=None, set_name='', log=None,
                 progress=None):
    """Generate `count` mazes into out_dir/<maze name>/. Returns the list of maze folders."""
    errors, _ = validate(params, profile)
    if errors:
        raise GenerationError('; '.join(errors))
    seen = set()
    folders = []
    for i in range(count):
        maze, discarded = generate_checked(params, derive_seed(set_seed, i), seen, log)
        seen.add('\n'.join(_layout_key(maze)))
        folder = os.path.join(out_dir, maze_name(i))
        for name, data in build_files(maze, i, set_seed, discarded, profile, set_name).items():
            fileio.write_bytes(os.path.join(folder, name), data)
        folders.append(folder)
        if progress:
            progress(i + 1, count)
    return folders


def set_digest(folder_list):
    """A hash of all maze files of a set, to confirm two generations are identical."""
    h = hashlib.sha256()
    for folder in folder_list:
        for name in ('world.sdf', 'layout.txt', 'maze.json', 'preview.png'):
            with open(os.path.join(folder, name), 'rb') as f:
                h.update(f.read())
    return h.hexdigest()


def load_maze_meta(folder):
    return fileio.read_json(os.path.join(folder, 'maze.json'))
